# Gradient reversal class for DANN domain adaptation
class GradientReversalFunction(Function):
    @staticmethod
    def forward(ctx, x, alpha):
        ctx.alpha = alpha
        return x

    @staticmethod
    def backward(ctx, grad_output):
        return -ctx.alpha * grad_output, None


class Dsanformer(nn.Module):
    """ Transformer """
    # Initialise the Transformer
    def __init__(self,
                 d_input: int,
                 d_channel: int,
                 d_model: int,
                 d_output: int,
                 q: int,
                 v: int,
                 h: int,
                 N: int,
                 dropout: float = 0.3,
                 pe: bool = False):
        super().__init__()

        self._d_input = d_input
        self._d_channel = d_channel
        self._d_model = d_model
        self._pe = pe

        self.layers_encoding = nn.ModuleList([Encoder(d_model,
                                                      q,
                                                      v,
                                                      h,
                                                      dropout=dropout) for _ in range(N)])

        # Classificiation layer for attention outputs
        self._embedding = nn.Linear(self._d_channel, d_model)
        self._linear = nn.Linear(d_model * d_input, d_output)


    # Transformer forward pass
    def forward(self, x: torch.Tensor, grl_lambda=1.0) -> torch.Tensor:

        encoding = self._embedding(x)

        # Positional encoding
        if self._pe:
            pe = torch.ones_like(encoding[0])
            position = torch.arange(0, self._d_input).unsqueeze(-1)
            temp = torch.Tensor(range(0, self._d_model, 2))
            temp = temp * -(math.log(10000)/self._d_model)
            temp = torch.exp(temp).unsqueeze(0)
            # shape:[input, d_model/2]
            temp = torch.matmul(position.float(), temp)
            pe[:, 0::2] = torch.sin(temp)
            pe[:, 1::2] = torch.cos(temp)
            encoding = encoding + pe

        # Encoding stack
        for layer in self.layers_encoding:
            encoding = layer(encoding)

        encoding = encoding.reshape(encoding.shape[0], -1)

        return encoding


class PositionwiseFeedForward(nn.Module):

    """ Position-wise Feed Forward Network block from Attention is All You Need. """
    def __init__(self,
                 d_model: int,
                 d_ff: Optional[int] = 2048):
        super().__init__()
        self._linear1 = nn.Linear(d_model, d_ff)
        self._linear2 = nn.Linear(d_ff, d_model)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        return self._linear2(F.relu(self._linear1(x)))


class MultiHeadAttention(nn.Module):
    """Multi Head Attention block from Attention is All You Need."""

    def __init__(self,
                 d_model: int,
                 q: int,
                 v: int,
                 h: int):
        super().__init__()

        self._q = q
        self._h = h

        # Query, keys and value matrices
        self._W_q = nn.Linear(d_model, q * h)
        self._W_k = nn.Linear(d_model, q * h)
        self._W_v = nn.Linear(d_model, v * h)

        # Output linear function
        self._W_o = nn.Linear(v * h, d_model)

        # Score placeholder
        self._scores = None

    def forward(self,
                query: torch.Tensor,
                key: torch.Tensor,
                value: torch.Tensor,
                mask: Optional[str] = None) -> torch.Tensor:

        # Query, keys and values
        Q = torch.cat(self._W_q(query).chunk(self._h, dim=-1), dim=0)
        K = torch.cat(self._W_k(key).chunk(self._h, dim=-1), dim=0)
        V = torch.cat(self._W_v(value).chunk(self._h, dim=-1), dim=0)

        self._scores = torch.matmul(
            Q, K.transpose(-1, -2)) / math.sqrt(self._q)  # Scaled Dot Product
        # Apply softmax: shape [batchsize * head_num, input, input]
        self._scores = F.softmax(self._scores, dim=-1)
        attention = torch.matmul(self._scores, V)  # scores * values
        attention_heads = torch.cat(attention.chunk(
            self._h, dim=0), dim=-1)  # Concatenat the heads
        # Apply linear transformation W^O shape [batchsize, input, d_model]
        self_attention = self._W_o(attention_heads)
        return self_attention


class Encoder(nn.Module):
    """Encoder block from Attention is All You Need."""

    def __init__(self,
                 d_model: int,
                 q: int,
                 v: int,
                 h: int,
                 dropout: float = 0.3):
        super().__init__()

        MHA = MultiHeadAttention
        self._selfAttention = MHA(d_model, q, v, h)
        self._feedForward = PositionwiseFeedForward(d_model)

        self._layerNorm1 = nn.LayerNorm(d_model)
        self._layerNorm2 = nn.LayerNorm(d_model)

        self._dropout = nn.Dropout(p=dropout)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        """Propagate the input through the Encoder block.
        Apply the Multi Head Attention block, add residual and normalize.
        Apply the Point-wise Feed Forward block."""
        # Self attention
        residual = x
        x = self._selfAttention(query=x, key=x, value=x)
        x = self._dropout(x)
        x = self._layerNorm1(x + residual)

        # Feed forward
        residual = x
        x = self._feedForward(x)
        x = self._dropout(x)
        x = self._layerNorm2(x + residual)
        return

